#!/usr/bin/env bash
# Adaptive 全库检索：复用已选视角，输出 dense/sparse/hybrid；不重排、不重新选择、不支持 overlap。
set -euo pipefail
REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"
# STC configuration must match candidate encoding; search only reads existing mappings.
USE_STC_SPARSE="${USE_STC_SPARSE-false}"
STC_ALGORITHM="${STC_ALGORITHM-agglomerative}" # agglomerative / minibatch_kmeans
STC_N_CLUSTERS="${STC_N_CLUSTERS-16000}" # semantic clusters; numeric dimensions are additional
STC_SEED="${STC_SEED-42}"
STC_BATCH_SIZE="${STC_BATCH_SIZE-4096}"
STC_MAX_ITER="${STC_MAX_ITER-100}"
STC_WEIGHT_SCALE="${STC_WEIGHT_SCALE-100}"
STC_CACHE_ROOT="${STC_CACHE_ROOT-}" # automatic lookup: SPARSE_OUTPUT_ROOT/stc_vocab
source "${REPO_ROOT}/scripts/stc_sparse_mode.sh" || exit $?
# LENS centroid LM head; false preserves the original/STC representation.
USE_LENS_SPARSE="${USE_LENS_SPARSE-false}"
LENS_ALGORITHM="${LENS_ALGORITHM-kmeans}" # kmeans / minibatch_kmeans
LENS_N_CLUSTERS="${LENS_N_CLUSTERS-8000}"
LENS_SEED="${LENS_SEED-42}"
LENS_N_INIT="${LENS_N_INIT-1}"
LENS_MAX_ITER="${LENS_MAX_ITER-300}"
LENS_BATCH_SIZE="${LENS_BATCH_SIZE-4096}" # MiniBatch only
LENS_CACHE_ROOT="${LENS_CACHE_ROOT-}" # empty: SPARSE_OUTPUT_ROOT/lens_heads
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/lens_sparse_mode.sh" || exit $?
if (($#)) && ! { (($# == 1)) && [[ "$1" == -h || "$1" == --help ]]; }; then
    echo 'Configure variables below or in the environment; see --help.' >&2
    exit 2
fi

# ===== 模型、数据集与方向：空格分隔，非空单值覆盖列表 =====
MODEL_FAMILIES="${MODEL_FAMILIES-qwen2 qwen25 qwen3 llava_llama llava_mistral}"
MODEL_FAMILY="${MODEL_FAMILY-}"
DATASETS="${DATASETS-webqa remuq llava}"
DATASET="${DATASET-}"
DATASET_SPLIT="${DATASET_SPLIT-test}"
IR_QUERY_TYPES="${IR_QUERY_TYPES-text image}" # 仅 IR；TBPR/WebQA=text，ReMuQ/LLaVA=图文查询
IR_QUERY_TYPE="${IR_QUERY_TYPE-}"
CHECKPOINT_ROOT="${CHECKPOINT_ROOT-/root/autodl-fs/checkpoints}"
MODEL_PATH_QWEN2="${MODEL_PATH_QWEN2-${CHECKPOINT_ROOT}/Qwen-Qwen2-VL-7B-Instruct}"
MODEL_PATH_QWEN25="${MODEL_PATH_QWEN25-${CHECKPOINT_ROOT}/Qwen-Qwen2.5-VL-7B-Instruct}"
MODEL_PATH_QWEN3="${MODEL_PATH_QWEN3-${CHECKPOINT_ROOT}/Qwen-Qwen3-VL-8B-Instruct}"
MODEL_PATH_LLAVA_LLAMA="${MODEL_PATH_LLAVA_LLAMA-${CHECKPOINT_ROOT}/llava-hf-llama3-llava-next-8b-hf}"
MODEL_PATH_LLAVA_MISTRAL="${MODEL_PATH_LLAVA_MISTRAL-${CHECKPOINT_ROOT}/llava-hf-llava-v1.6-mistral-7b-hf}"
MODEL_PATH="${MODEL_PATH-}" # 仅单模型族可指定

# ===== 目录：自动模式必须匹配原编码配置及模型/数据路径 =====
DATA_ROOT="${DATA_ROOT-/root/autodl-tmp}"
DENSE_OUTPUT_ROOT="${DENSE_OUTPUT_ROOT-./dense_output}"
SPARSE_OUTPUT_ROOT="${SPARSE_OUTPUT_ROOT-./sparse_output}"
VIEW_SELECTION_ROOT="${VIEW_SELECTION_ROOT-${SPARSE_OUTPUT_ROOT}/view_selection}"
SEARCH_OUTPUT_ROOT="${SEARCH_OUTPUT_ROOT-./adaptive_search_results}"
OUTPUT_DIR="${OUTPUT_DIR-}" # 手动输出目录，仅单任务
# 任一候选目录非空即手动模式；仅单任务，不再计算编码产物路径。
# 单独填写 dense 或 sparse 可只检索该路；两者均填写则同时输出 hybrid。
DENSE_CORPUS_DIR="${DENSE_CORPUS_DIR-}"
# Prefer collection/index; build it with sparse_index_adaptive_fused.sh first. Search never creates indexes.
SPARSE_CORPUS_DIR="${SPARSE_CORPUS_DIR-}"
VIEW_SELECTION_FILE="${VIEW_SELECTION_FILE-}" # 空时读取清单，绝不重新选择

# ===== 编码配置：与 encode_adaptive_views_fused.sh 对齐 =====
DTYPE="${DTYPE-float16}"
REPS_LOC="${REPS_LOC-after_pad}"
SPARSE_LENGTH="${SPARSE_LENGTH-40}"
TEXT_SPARSE_LENGTH="${TEXT_SPARSE_LENGTH-${SPARSE_LENGTH}}"
IMAGE_SPARSE_LENGTH="${IMAGE_SPARSE_LENGTH-${SPARSE_LENGTH}}"
SPARSE_VALUE_TYPE="${SPARSE_VALUE_TYPE-sum}"
SPARSE_LOWER_OR_UPPER="${SPARSE_LOWER_OR_UPPER-lower}"
SPARSE_VALUE_MEAN="${SPARSE_VALUE_MEAN-false}"
IS_FILTERED="${IS_FILTERED-false}"
NUM_EXPENDED_TOKENS="${NUM_EXPENDED_TOKENS-0}"
TBPR_TYPE="${TBPR_TYPE-origin_type}"
LLAVA_IMAGE_MODE="${LLAVA_IMAGE_MODE-anyres}" # base 只可选择 LLaVA；Qwen 必须为 anyres
QWEN_MIN_PIXELS="${QWEN_MIN_PIXELS-0}"
QWEN_MAX_PIXELS="${QWEN_MAX_PIXELS-0}"
# 固定 disassembleeol_separate / concat / sparse_manual=false / prompt_5。

# ===== 保存的视角选择配置：仅用于精确定位与校验 =====
VIEW_SELECTION_SPLIT="${VIEW_SELECTION_SPLIT-}"
VIEW_SELECTION_MODALITY="${VIEW_SELECTION_MODALITY-both}"
USE_VIEW_PMI="${USE_VIEW_PMI-false}"
USE_HIERARCHICAL_VIEWS="${USE_HIERARCHICAL_VIEWS-false}"
VIEW_SELECTION_ROUNDS="${VIEW_SELECTION_ROUNDS-20}"
VIEW_SELECTION_SEED="${VIEW_SELECTION_SEED-42}"
VIEW_EXAMPLE_MODE="${VIEW_EXAMPLE_MODE-auto}"
VIEW_EXAMPLE_MAX_TOKENS="${VIEW_EXAMPLE_MAX_TOKENS-0}"
VIEW_TEXTS_PER_ROUND="${VIEW_TEXTS_PER_ROUND-8}" # fixed 模式的原采样数量
VIEW_IMAGES_PER_ROUND="${VIEW_IMAGES_PER_ROUND-2}"
SHUFFLE_VIEW_OPTIONS="${SHUFFLE_VIEW_OPTIONS-false}"
VIEW_SELECTION_RUN_ID="${VIEW_SELECTION_RUN_ID-}" # 填写编码时的 run ID，检索不会生成新 ID
USE_VIEW_PROBABILITY_MASS="${USE_VIEW_PROBABILITY_MASS-false}"
VIEW_PROBABILITY_MASS_THRESHOLD="${VIEW_PROBABILITY_MASS_THRESHOLD-0.9}" # v2：加入前判断，至少保留第一项

# ===== FreeRet 表征：必须与候选编码一致，完整提示词优先 =====
USE_FREERET_DENSE="${USE_FREERET_DENSE-false}"
USE_FREERET_PROMPT_CONSTRAINTS="${USE_FREERET_PROMPT_CONSTRAINTS-false}"
USE_FREERET_FULL_PROMPT="${USE_FREERET_FULL_PROMPT-false}"

# ===== 全库检索与融合 =====
DEPTH="${DEPTH-1000}" # 每路全库检索深度；无 stage1/stage2 候选范围限制
HYBRID_ALPHA="${HYBRID_ALPHA-0.5}" # dense 权重；sparse 为 1-alpha
SELECT_HYBRID_ALPHA="${SELECT_HYBRID_ALPHA-false}" # true 扫描 0.1..0.9，否则固定 HYBRID_ALPHA
RETRIEVAL_BATCH_SIZE="${RETRIEVAL_BATCH_SIZE-1}"
THREADS="${THREADS-16}"
USE_GPU="${USE_GPU-false}" # FAISS 索引使用 GPU；模型仍默认使用可用 CUDA
# 验证库仅单任务、自动选权重时使用；不填则在目标集选择并明确标注来源。
VAL_PASSAGE_REPS="${VAL_PASSAGE_REPS-}"
VAL_SPARSE_INDEX="${VAL_SPARSE_INDEX-}"
VAL_VIEW_SELECTION_FILE="${VAL_VIEW_SELECTION_FILE-}"
VALIDATION_DATASET_NAME="${VALIDATION_DATASET_NAME-}"
VALIDATION_SPLIT="${VALIDATION_SPLIT-val}"

# ===== 执行资源 =====
GPUS="${GPUS-1}"
NUM_NODES="${NUM_NODES-1}"
DRY_RUN="${DRY_RUN-false}" # 只校验和打印，不加载模型权重、不写文件
OVERWRITE="${OVERWRITE-false}"
PYTHON_BIN="${PYTHON_BIN:-python}"
DEEPSPEED_BIN="${DEEPSPEED_BIN:-deepspeed}"
command -v "${PYTHON_BIN}" >/dev/null 2>&1 || { echo "Python not found: ${PYTHON_BIN}" >&2; exit 2; }
BATCH_ENV=("${STC_ENV[@]}" "${LENS_ENV[@]}")
for name in MODEL_FAMILIES MODEL_FAMILY DATASETS DATASET DATASET_SPLIT IR_QUERY_TYPES IR_QUERY_TYPE \
    CHECKPOINT_ROOT MODEL_PATH_QWEN2 MODEL_PATH_QWEN25 MODEL_PATH_QWEN3 MODEL_PATH_LLAVA_LLAMA MODEL_PATH_LLAVA_MISTRAL MODEL_PATH \
    DATA_ROOT DENSE_OUTPUT_ROOT SPARSE_OUTPUT_ROOT VIEW_SELECTION_ROOT SEARCH_OUTPUT_ROOT OUTPUT_DIR \
    DENSE_CORPUS_DIR SPARSE_CORPUS_DIR VIEW_SELECTION_FILE DTYPE REPS_LOC SPARSE_LENGTH TEXT_SPARSE_LENGTH IMAGE_SPARSE_LENGTH \
    SPARSE_VALUE_TYPE SPARSE_LOWER_OR_UPPER SPARSE_VALUE_MEAN IS_FILTERED NUM_EXPENDED_TOKENS TBPR_TYPE \
    LLAVA_IMAGE_MODE QWEN_MIN_PIXELS QWEN_MAX_PIXELS VIEW_SELECTION_SPLIT VIEW_SELECTION_MODALITY USE_VIEW_PMI \
    USE_HIERARCHICAL_VIEWS VIEW_SELECTION_ROUNDS VIEW_SELECTION_SEED VIEW_EXAMPLE_MODE VIEW_EXAMPLE_MAX_TOKENS \
    VIEW_TEXTS_PER_ROUND VIEW_IMAGES_PER_ROUND SHUFFLE_VIEW_OPTIONS VIEW_SELECTION_RUN_ID \
    USE_VIEW_PROBABILITY_MASS VIEW_PROBABILITY_MASS_THRESHOLD USE_FREERET_DENSE USE_FREERET_PROMPT_CONSTRAINTS USE_FREERET_FULL_PROMPT \
    DEPTH HYBRID_ALPHA SELECT_HYBRID_ALPHA RETRIEVAL_BATCH_SIZE THREADS USE_GPU VAL_PASSAGE_REPS VAL_SPARSE_INDEX \
    VAL_VIEW_SELECTION_FILE VALIDATION_DATASET_NAME VALIDATION_SPLIT GPUS NUM_NODES DRY_RUN OVERWRITE DEEPSPEED_BIN; do
    BATCH_ENV+=("${name}=${!name}")
done
exec env "${BATCH_ENV[@]}" "${PYTHON_BIN}" -B src/adaptive_search_batch.py --task-group fused "$@"
