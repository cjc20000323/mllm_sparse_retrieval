#!/usr/bin/env bash
# 一次调用：同一概率排序 -> Top-1..7 稀疏编码 -> 建索引 -> 二/三阶段检索 -> CSV 汇总。
# 所有任务由新的 Python 入口执行；不调用或修改原有编码、检索启动脚本。
set -euo pipefail
REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"

# ===== 模型、数据集、方向：空格分隔即可批量执行 =====
MODEL_FAMILIES="${MODEL_FAMILIES-qwen25}" # qwen2 qwen25 qwen3 llava_llama llava_mistral
MODEL_FAMILY="${MODEL_FAMILY-}"          # 非空覆盖 MODEL_FAMILIES
DATASETS="${DATASETS-flickr}"           # flickr coco CUHK-PEDES ICFG-PEDES RSTPReid webqa remuq llava
DATASET="${DATASET-}"                   # 非空覆盖 DATASETS
IR_QUERY_TYPES="${IR_QUERY_TYPES-text}"  # text / image / 'text image'，仅 IR 使用
IR_QUERY_TYPE="${IR_QUERY_TYPE-}"
DATASET_SPLIT="${DATASET_SPLIT-test}"
# TBPR=text->image；WebQA=text->图文；ReMuQ/LLaVA=图文->text。

# ===== 路径 =====
CHECKPOINT_ROOT="${CHECKPOINT_ROOT-/root/autodl-fs/checkpoints}"
MODEL_PATH_QWEN2="${MODEL_PATH_QWEN2-${CHECKPOINT_ROOT}/Qwen-Qwen2-VL-7B-Instruct}"
MODEL_PATH_QWEN25="${MODEL_PATH_QWEN25-${CHECKPOINT_ROOT}/Qwen-Qwen2.5-VL-7B-Instruct}"
MODEL_PATH_QWEN3="${MODEL_PATH_QWEN3-${CHECKPOINT_ROOT}/Qwen-Qwen3-VL-8B-Instruct}"
MODEL_PATH_LLAVA_LLAMA="${MODEL_PATH_LLAVA_LLAMA-${CHECKPOINT_ROOT}/llava-hf-llama3-llava-next-8b-hf}"
MODEL_PATH_LLAVA_MISTRAL="${MODEL_PATH_LLAVA_MISTRAL-${CHECKPOINT_ROOT}/llava-hf-llava-v1.6-mistral-7b-hf}"
MODEL_PATH="${MODEL_PATH-}"              # 仅单模型族允许全局覆盖
DATA_ROOT="${DATA_ROOT-/root/autodl-tmp}"
SPARSE_OUTPUT_ROOT="${SPARSE_OUTPUT_ROOT-./sparse_output}" # 仅用于定位/保存原概率选择缓存
OUTPUT_ROOT="${OUTPUT_ROOT-./adaptive_topk_results}"       # 新实验产物、索引及检索结果的独立根目录

# ===== 阶段控制与资源 =====
STOP_AFTER_STAGE2="${STOP_AFTER_STAGE2-false}" # true: 只到第二阶段，完全跳过重排；false: 全三阶段
DRY_RUN="${DRY_RUN-false}"                     # true: 预检并打印，不写文件或加载模型
GPUS="${GPUS-1}"
NUM_NODES="${NUM_NODES-1}"
DTYPE="${DTYPE-float16}"                      # float16 / bfloat16 / float32
PER_DEVICE_BATCH_SIZE="${PER_DEVICE_BATCH_SIZE-1}"
RETRIEVAL_BATCH_SIZE="${RETRIEVAL_BATCH_SIZE-1}"
PYTHON_BIN="${PYTHON_BIN:-python}"
DEEPSPEED_BIN="${DEEPSPEED_BIN:-deepspeed}"

# ===== 稀疏参数：每个视角保留 SPARSE_LENGTH 个 token，前 K 个视角再合并 =====
REPS_LOC="${REPS_LOC-after_pad}"
SPARSE_LENGTH="${SPARSE_LENGTH-40}"
TEXT_SPARSE_LENGTH="${TEXT_SPARSE_LENGTH-${SPARSE_LENGTH}}"
IMAGE_SPARSE_LENGTH="${IMAGE_SPARSE_LENGTH-${SPARSE_LENGTH}}"
SPARSE_VALUE_TYPE="${SPARSE_VALUE_TYPE-sum}"              # sum / max / replace
SPARSE_LOWER_OR_UPPER="${SPARSE_LOWER_OR_UPPER-lower}"
SPARSE_VALUE_MEAN="${SPARSE_VALUE_MEAN-false}"             # true 时分别除以各组实际的 K
IS_FILTERED="${IS_FILTERED-false}"
NUM_EXPENDED_TOKENS="${NUM_EXPENDED_TOKENS-0}"
TBPR_TYPE="${TBPR_TYPE-origin_type}"
# 固定沿用 disassembleeol_separate / concat / sparse_manual=false / prompt_5 / random_view_seed=42。

# ===== 图像处理 =====
LLAVA_IMAGE_MODE="${LLAVA_IMAGE_MODE-anyres}" # base 只用于 LLaVA-NeXT，Qwen 使用 anyres
QWEN_MIN_PIXELS="${QWEN_MIN_PIXELS-0}"
QWEN_MAX_PIXELS="${QWEN_MAX_PIXELS-0}"

# ===== 概率来源：每个模型/数据集只计算一次，七组和 IR 双向共用 =====
VIEW_SELECTION_FILE="${VIEW_SELECTION_FILE-}" # 可填写原 encode_adaptive_views 的 view_selection.json；限单模型/数据集
VIEW_SELECTION_SPLIT="${VIEW_SELECTION_SPLIT-}"
VIEW_SELECTION_MODALITY="${VIEW_SELECTION_MODALITY-}" # 空: 新选择用 both，已有文件继承；text / image / both
USE_VIEW_PMI="${USE_VIEW_PMI-}"                       # 空: 新选择 false，已有文件继承；true 按 PMI 校正概率排序
USE_HIERARCHICAL_VIEWS="${USE_HIERARCHICAL_VIEWS-}"     # 空: 新选择 false，已有文件继承；true 为十个层级候选
VIEW_SELECTION_ROUNDS="${VIEW_SELECTION_ROUNDS-20}"
VIEW_SELECTION_SEED="${VIEW_SELECTION_SEED-42}"
VIEW_EXAMPLE_MODE="${VIEW_EXAMPLE_MODE-auto}"
VIEW_EXAMPLE_MAX_TOKENS="${VIEW_EXAMPLE_MAX_TOKENS-0}" # auto 总预算；0 使用模型上下文上限
VIEW_TEXTS_PER_ROUND="${VIEW_TEXTS_PER_ROUND-8}"       # 仅 fixed 模式使用
VIEW_IMAGES_PER_ROUND="${VIEW_IMAGES_PER_ROUND-2}"
SHUFFLE_VIEW_OPTIONS="${SHUFFLE_VIEW_OPTIONS-false}"
VIEW_SELECTION_RUN_ID="${VIEW_SELECTION_RUN_ID-}"     # 新打乱实验留空；指定原 16 位 ID 可复用对应缓存
# 指定已有选择文件时保留文件中的采样与选项映射；不执行 overlap 筛选。

# ===== 表征模式：沿用现有提示词和表征实现 =====
USE_FREERET_DENSE="${USE_FREERET_DENSE-false}"
USE_FREERET_PROMPT_CONSTRAINTS="${USE_FREERET_PROMPT_CONSTRAINTS-false}"
USE_FREERET_FULL_PROMPT="${USE_FREERET_FULL_PROMPT-false}"

# ===== 检索参数：七组共用固定融合权重 =====
STAGE1_DEPTH="${STAGE1_DEPTH-1000}"
STAGE2_DEPTH="${STAGE2_DEPTH-1000}"
SPARSE_THREADS="${SPARSE_THREADS-16}"
HYBRID_ALPHA="${HYBRID_ALPHA-0.5}" # dense 权重；sparse 权重为 1-alpha

# ===== 重排参数：STOP_AFTER_STAGE2=true 时这些配置不参与校验或加载 =====
RANKER_MODEL_PATH="${RANKER_MODEL_PATH-}" # 空时与当前检索模型相同
RANKER_MODEL_PATH_QWEN2="${RANKER_MODEL_PATH_QWEN2-}"
RANKER_MODEL_PATH_QWEN25="${RANKER_MODEL_PATH_QWEN25-}"
RANKER_MODEL_PATH_QWEN3="${RANKER_MODEL_PATH_QWEN3-}"
RANKER_MODEL_PATH_LLAVA_LLAMA="${RANKER_MODEL_PATH_LLAVA_LLAMA-}"
RANKER_MODEL_PATH_LLAVA_MISTRAL="${RANKER_MODEL_PATH_LLAVA_MISTRAL-}"
RANKER_DTYPE="${RANKER_DTYPE-${DTYPE}}"
RANKER_LLAVA_IMAGE_MODE="${RANKER_LLAVA_IMAGE_MODE-${LLAVA_IMAGE_MODE}}"
RANKER_QWEN_MIN_PIXELS="${RANKER_QWEN_MIN_PIXELS-${QWEN_MIN_PIXELS}}"
RANKER_QWEN_MAX_PIXELS="${RANKER_QWEN_MAX_PIXELS-${QWEN_MAX_PIXELS}}"
RERANK_NUM="${RERANK_NUM-5}"
RERANK_BATCH_SIZE="${RERANK_BATCH_SIZE-1}"
# pointwise / what_caption_generation；modify_type 按任务方向自动确定。

command -v "${PYTHON_BIN}" >/dev/null 2>&1 || { echo "Python not found: ${PYTHON_BIN}" >&2; exit 2; }
BATCH_ENV=()
for name in MODEL_FAMILIES MODEL_FAMILY DATASETS DATASET IR_QUERY_TYPES IR_QUERY_TYPE DATASET_SPLIT \
    CHECKPOINT_ROOT MODEL_PATH MODEL_PATH_QWEN2 MODEL_PATH_QWEN25 MODEL_PATH_QWEN3 MODEL_PATH_LLAVA_LLAMA MODEL_PATH_LLAVA_MISTRAL \
    DATA_ROOT SPARSE_OUTPUT_ROOT OUTPUT_ROOT STOP_AFTER_STAGE2 DRY_RUN GPUS NUM_NODES DTYPE PER_DEVICE_BATCH_SIZE RETRIEVAL_BATCH_SIZE \
    DEEPSPEED_BIN REPS_LOC SPARSE_LENGTH TEXT_SPARSE_LENGTH IMAGE_SPARSE_LENGTH SPARSE_VALUE_TYPE SPARSE_LOWER_OR_UPPER \
    SPARSE_VALUE_MEAN IS_FILTERED NUM_EXPENDED_TOKENS TBPR_TYPE LLAVA_IMAGE_MODE QWEN_MIN_PIXELS QWEN_MAX_PIXELS \
    VIEW_SELECTION_FILE VIEW_SELECTION_SPLIT VIEW_SELECTION_MODALITY USE_VIEW_PMI USE_HIERARCHICAL_VIEWS VIEW_SELECTION_ROUNDS \
    VIEW_SELECTION_SEED VIEW_EXAMPLE_MODE VIEW_EXAMPLE_MAX_TOKENS VIEW_TEXTS_PER_ROUND VIEW_IMAGES_PER_ROUND \
    SHUFFLE_VIEW_OPTIONS VIEW_SELECTION_RUN_ID USE_FREERET_DENSE USE_FREERET_PROMPT_CONSTRAINTS USE_FREERET_FULL_PROMPT \
    STAGE1_DEPTH STAGE2_DEPTH SPARSE_THREADS HYBRID_ALPHA RANKER_MODEL_PATH RANKER_MODEL_PATH_QWEN2 RANKER_MODEL_PATH_QWEN25 \
    RANKER_MODEL_PATH_QWEN3 RANKER_MODEL_PATH_LLAVA_LLAMA RANKER_MODEL_PATH_LLAVA_MISTRAL RANKER_DTYPE \
    RANKER_LLAVA_IMAGE_MODE RANKER_QWEN_MIN_PIXELS RANKER_QWEN_MAX_PIXELS RERANK_NUM RERANK_BATCH_SIZE; do
    BATCH_ENV+=("${name}=${!name}")
done
exec env "${BATCH_ENV[@]}" "${PYTHON_BIN}" -B src/adaptive_views_topk_experiment.py "$@"
