#!/usr/bin/env bash
# auto 按实际上下文长度填充示例；fixed 使用 VIEW_TEXTS_PER_ROUND / VIEW_IMAGES_PER_ROUND。
VIEW_EXAMPLE_MODE="${VIEW_EXAMPLE_MODE-auto}"
VIEW_EXAMPLE_MAX_TOKENS="${VIEW_EXAMPLE_MAX_TOKENS-0}" # 0 使用模型上限；可下调，总预算包含一个回答 token
# 自动按编码配置定位 IR 指纹；非空 TARGET_SPARSE_DIR 改为手动指定实验目录。
set -euo pipefail
REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"
if (($#)) && ! { (($# == 1)) && [[ "$1" == -h || "$1" == --help ]]; }; then
    echo 'Configure environment variables or the configuration block; see --help.' >&2
    exit 2
fi

# ===== 自动定位 / 手动指定 =====
# 留空时用编码配置计算缓存位置，读取真实视角指纹；不会扫描历史实验。
# 手动模式填写编码日志中 Adaptive sparse 的完整目录（含 adaptive_views_manifest.json）。
TARGET_SPARSE_DIR="${TARGET_SPARSE_DIR-}"
MODEL_FAMILIES="${MODEL_FAMILIES-qwen2 qwen25 qwen3 llava_llama llava_mistral}"
MODEL_FAMILY="${MODEL_FAMILY-}"
DATASETS="${DATASETS-flickr coco}"
DATASET="${DATASET-}"
ENCODE_TYPES="${ENCODE_TYPES-image text}"
ENCODE_TYPE="${ENCODE_TYPE-}"
DATASET_SPLIT="${DATASET_SPLIT-test}"
# image/text 分别对应图像和文本候选库，共用模型/数据集的锁定视角。

# ===== 检查点及数据目录：必须与编码时一致 =====
CHECKPOINT_ROOT="${CHECKPOINT_ROOT-/root/autodl-fs/checkpoints}"
MODEL_PATH_QWEN2="${MODEL_PATH_QWEN2-${CHECKPOINT_ROOT}/Qwen-Qwen2-VL-7B-Instruct}"
MODEL_PATH_QWEN25="${MODEL_PATH_QWEN25-${CHECKPOINT_ROOT}/Qwen-Qwen2.5-VL-7B-Instruct}"
MODEL_PATH_QWEN3="${MODEL_PATH_QWEN3-${CHECKPOINT_ROOT}/Qwen-Qwen3-VL-8B-Instruct}"
MODEL_PATH_LLAVA_LLAMA="${MODEL_PATH_LLAVA_LLAMA-${CHECKPOINT_ROOT}/llava-hf-llama3-llava-next-8b-hf}"
MODEL_PATH_LLAVA_MISTRAL="${MODEL_PATH_LLAVA_MISTRAL-${CHECKPOINT_ROOT}/llava-hf-llava-v1.6-mistral-7b-hf}"
MODEL_PATH="${MODEL_PATH-}"              # 非空时只允许一个模型族
DATA_ROOT="${DATA_ROOT-/root/autodl-tmp}" # 参与缓存键；索引阶段不读取原始数据
SPARSE_OUTPUT_ROOT="${SPARSE_OUTPUT_ROOT-./sparse_output}"
DENSE_OUTPUT_ROOT="${DENSE_OUTPUT_ROOT-./dense_output}" # 仅供路径函数使用，不读取 dense 文件
VIEW_SELECTION_ROOT="${VIEW_SELECTION_ROOT-${SPARSE_OUTPUT_ROOT}/view_selection}" # 恢复清单中缺失的原引用

# ===== 编码精度、稀疏参数及图像处理 =====
DTYPE="${DTYPE-float16}"
REPS_LOC="${REPS_LOC-after_pad}"
SPARSE_LENGTH="${SPARSE_LENGTH-40}"
TEXT_SPARSE_LENGTH="${TEXT_SPARSE_LENGTH-${SPARSE_LENGTH}}"
IMAGE_SPARSE_LENGTH="${IMAGE_SPARSE_LENGTH-${SPARSE_LENGTH}}"
SPARSE_VALUE_TYPE="${SPARSE_VALUE_TYPE-sum}"
SPARSE_LOWER_OR_UPPER="${SPARSE_LOWER_OR_UPPER-lower}"
SPARSE_VALUE_MEAN="${SPARSE_VALUE_MEAN-false}"
IS_FILTERED="${IS_FILTERED-false}"
NUM_EXPENDED_TOKENS="${NUM_EXPENDED_TOKENS-0}"
TBPR_TYPE="${TBPR_TYPE-origin_type}"
LLAVA_IMAGE_MODE="${LLAVA_IMAGE_MODE-anyres}" # base 仅支持 LLaVA-NeXT
QWEN_MIN_PIXELS="${QWEN_MIN_PIXELS-0}"
QWEN_MAX_PIXELS="${QWEN_MAX_PIXELS-0}"
# 固定值与编码脚本一致：concat / prompt_5 / disassembleeol_separate / sparse_manual=false。

# ===== 视角选择：匹配原编码配置，不会重新选择或探测 =====
VIEW_SELECTION_SPLIT="${VIEW_SELECTION_SPLIT-}" # 空时跟随 DATASET_SPLIT
VIEW_SELECTION_MODALITY="${VIEW_SELECTION_MODALITY-both}"
VIEW_SELECTION_ROUNDS="${VIEW_SELECTION_ROUNDS-20}"
VIEW_TEXTS_PER_ROUND="${VIEW_TEXTS_PER_ROUND-8}"
VIEW_IMAGES_PER_ROUND="${VIEW_IMAGES_PER_ROUND-2}"
VIEW_SELECTION_SEED="${VIEW_SELECTION_SEED-42}"
USE_VIEW_PMI="${USE_VIEW_PMI-false}"
USE_HIERARCHICAL_VIEWS="${USE_HIERARCHICAL_VIEWS-false}"
USE_VIEW_OVERLAP_SELECTION="${USE_VIEW_OVERLAP_SELECTION-false}"
VIEW_SELECTED_COUNT="${VIEW_SELECTED_COUNT-5}"
VIEW_OVERLAP_THRESHOLD="${VIEW_OVERLAP_THRESHOLD-0.1}"
VIEW_OVERLAP_SAMPLES="${VIEW_OVERLAP_SAMPLES-20}"
VIEW_OVERLAP_SEED="${VIEW_OVERLAP_SEED-42}"
SHUFFLE_VIEW_OPTIONS="${SHUFFLE_VIEW_OPTIONS-false}"
VIEW_SELECTION_RUN_ID="${VIEW_SELECTION_RUN_ID-}" # 打乱模式填写编码时的原 run ID，索引不生成新值
USE_FREERET_DENSE="${USE_FREERET_DENSE-false}"
USE_FREERET_FULL_PROMPT="${USE_FREERET_FULL_PROMPT-false}"  # Complete FreeRet dense/sparse prompts; requires FreeRet dense
USE_FREERET_PROMPT_CONSTRAINTS="${USE_FREERET_PROMPT_CONSTRAINTS-false}"
source "${REPO_ROOT}/scripts/freeret_dense_mode.sh"

# ===== 索引参数 =====
THREADS="${THREADS-${SPARSE_THREADS-16}}"
PMI_MODE="${PMI_MODE-all}" # 手动模式的筛选；自动模式以 USE_VIEW_PMI 精确定位
DRY_RUN="${DRY_RUN-false}" # true 只校验和打印，不建立索引
PYTHON_BIN="${PYTHON_BIN:-python}"
command -v "${PYTHON_BIN}" >/dev/null 2>&1 || { echo "Python not found: ${PYTHON_BIN}; activate the indexing environment or set PYTHON_BIN." >&2; exit 2; }
EXTRA=()
if [[ -n "${TARGET_SPARSE_DIR}" ]]; then
    if (($# == 0)) && [[ ! -f "${TARGET_SPARSE_DIR}/adaptive_views_manifest.json" ]]; then
        printf 'Error: TARGET_SPARSE_DIR must contain adaptive_views_manifest.json: %s\n' "${TARGET_SPARSE_DIR}" >&2
        exit 2
    fi
    SPARSE_OUTPUT_ROOT="${TARGET_SPARSE_DIR}"
else
    EXTRA+=(--exact-encoding)
fi
# 普通变量配置，在进入 Python 时集中传入；支持多模型、多数据集。
BATCH_ENV=()
for name in VIEW_EXAMPLE_MODE VIEW_EXAMPLE_MAX_TOKENS MODEL_FAMILIES MODEL_FAMILY DATASETS DATASET ENCODE_TYPES ENCODE_TYPE DATASET_SPLIT \
    CHECKPOINT_ROOT MODEL_PATH_QWEN2 MODEL_PATH_QWEN25 MODEL_PATH_QWEN3 MODEL_PATH_LLAVA_LLAMA MODEL_PATH_LLAVA_MISTRAL MODEL_PATH \
    DATA_ROOT SPARSE_OUTPUT_ROOT DENSE_OUTPUT_ROOT VIEW_SELECTION_ROOT DTYPE REPS_LOC \
    SPARSE_LENGTH TEXT_SPARSE_LENGTH IMAGE_SPARSE_LENGTH SPARSE_VALUE_TYPE SPARSE_LOWER_OR_UPPER \
    SPARSE_VALUE_MEAN IS_FILTERED NUM_EXPENDED_TOKENS TBPR_TYPE LLAVA_IMAGE_MODE QWEN_MIN_PIXELS QWEN_MAX_PIXELS \
    VIEW_SELECTION_SPLIT VIEW_SELECTION_MODALITY VIEW_SELECTION_ROUNDS VIEW_TEXTS_PER_ROUND VIEW_IMAGES_PER_ROUND VIEW_SELECTION_SEED \
    USE_VIEW_PMI USE_HIERARCHICAL_VIEWS USE_VIEW_OVERLAP_SELECTION VIEW_SELECTED_COUNT VIEW_OVERLAP_THRESHOLD VIEW_OVERLAP_SAMPLES VIEW_OVERLAP_SEED \
    SHUFFLE_VIEW_OPTIONS VIEW_SELECTION_RUN_ID USE_FREERET_DENSE USE_FREERET_PROMPT_CONSTRAINTS USE_FREERET_FULL_PROMPT THREADS PMI_MODE DRY_RUN; do
    BATCH_ENV+=("${name}=${!name}")
done
exec env "${BATCH_ENV[@]}" "${PYTHON_BIN}" -B src/adaptive_sparse_index_batch.py --task-group ir "${EXTRA[@]}" "$@"
