#!/usr/bin/env bash
# Shared transport only: editable defaults live in the public task launchers.
shared_views_task_main() {
    local action="$1" group="$2" name
    shift 2
    local repo_root
    repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
    cd "${repo_root}"
    # Export only public task settings; never print or copy unrelated environment values.
    for name in MODEL_FAMILY MODEL_FAMILIES MODEL_PATH MODEL_PATH_LLAVA_MISTRAL MODEL_PATH_LLAVA_LLAMA \
        DATASET DATASETS DATASET_SPLIT CHECKPOINT_ROOT DATA_ROOT DENSE_OUTPUT_ROOT SPARSE_OUTPUT_ROOT RESULT_ROOT \
        PROMPT_TYPE TBPR_TYPE GPUS NUM_NODES DTYPE PER_DEVICE_BATCH_SIZE PYTHON_BIN DEEPSPEED_BIN DRY_RUN \
        EOL_TYPE CALCULATE_TYPE SPARSE_MANUAL REPS_LOC SPARSE_LENGTH TEXT_SPARSE_LENGTH IMAGE_SPARSE_LENGTH \
        SPARSE_VALUE_TYPE SPARSE_LOWER_OR_UPPER SPARSE_VALUE_MEAN IS_FILTERED NUM_EXPENDED_TOKENS RANDOM_VIEW_SEED \
        LLAVA_IMAGE_MODE SPARSE_THREADS USE_FREERET_DENSE USE_FREERET_PROMPT_CONSTRAINTS USE_FREERET_FULL_PROMPT \
        DENSE_CORPUS_DIR SPARSE_CORPUS_DIR ENCODE_OUTPUT_DIR STAGE1_METHOD STAGE1_DEPTH STAGE2_DEPTH STAGE2_METHOD \
        HYBRID_ALPHA SELECT_HYBRID_ALPHA RETRIEVAL_MODEL_PATH RANKER_MODEL_PATH RANKER_MODEL_PATH_LLAVA_LLAMA \
        RANKER_MODEL_PATH_LLAVA_MISTRAL RETRIEVAL_DTYPE RANKER_DTYPE RETRIEVAL_REPS_LOC RETRIEVAL_LLAVA_IMAGE_MODE \
        RANKER_LLAVA_IMAGE_MODE RETRIEVAL_BATCH_SIZE RETRIEVAL_DEVICE RETRIEVAL_DEVICE_MAP RANKER_DEVICE_MAP \
        RERANK_NUM RERANK_BATCH_SIZE RERANK_TEMPLATE RERANK_TYPE MODIFY_TYPE RERANK_REPS_LOC OVERWRITE \
        USE_RERANK_PRIOR_CACHE RERANK_PRIOR_CACHE_DIR OUTPUT_DIR STAGE1_SPARSE_INDEX STAGE2_DENSE_INDEX STAGE2_SPARSE_INDEX \
        VAL_PASSAGE_REPS VAL_SPARSE_INDEX VALIDATION_DATASET_NAME VALIDATION_SPLIT VAL_STAGE1_SPARSE_INDEX VAL_STAGE1_RUN \
        BASE_MODEL ARTIFACT_MODEL_NAME QUERY_TYPE QUERY_TYPES ENCODE_TYPE TASK_TYPE STAGE1_RUN STAGE1_COMMAND STAGE2_RUN \
        RETRIEVAL_QWEN_MIN_PIXELS RETRIEVAL_QWEN_MAX_PIXELS RANKER_QWEN_MIN_PIXELS RANKER_QWEN_MAX_PIXELS; do
        if [[ -v "${name}" ]]; then export "${name}"; fi
    done
    exec "${PYTHON_BIN:-python}" -B src/standard_task_launchers.py "${action}" "${group}" "$@"
}
